import React, { useEffect, useState } from 'react';
import {
  Box,
  Typography,
  Stack,
  Button,
  Grid,
  Chip,
  Paper,
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  TextField,
  MenuItem,
  Slider,
  IconButton,
  Tooltip,
  Divider,
  Alert,
  Card,
  CardContent,
} from '@mui/material';
import { DataGrid, GridColDef } from '@mui/x-data-grid';
import { Add, Edit, Delete, PlayArrow, CheckCircle, Shield, PictureAsPdf, Visibility } from '@mui/icons-material';
import { useSnackbar } from 'notistack';

import { GlassCard } from '@/components/GlassCard';
import { PageHeader } from '@/components/PageHeader';
import { Watermark, WatermarkRule, WatermarkTestResult } from '../types/watermark.types';
import { watermarkService } from '../services/watermark.service';

export const WatermarkStudioPage: React.FC = () => {
  const { enqueueSnackbar } = useSnackbar();

  const [watermarks, setWatermarks] = useState<Watermark[]>([]);
  const [rules, setRules] = useState<WatermarkRule[]>([]);
  const [loading, setLoading] = useState(false);

  // Watermark Dialog
  const [wmDialogOpen, setWmDialogOpen] = useState(false);
  const [editingWm, setEditingWm] = useState<Partial<Watermark>>({
    name: '',
    type: 'DYNAMIC_TEXT',
    textTemplate: 'Generated by AITravelglobe for {{USER_NAME}}',
    fontSize: 18,
    fontColorHex: '#94A3B8',
    opacity: 0.25,
    rotationDegrees: -30,
    position: 'CENTER',
    repeatAcrossPage: true,
  });

  // Rule Dialog
  const [ruleDialogOpen, setRuleDialogOpen] = useState(false);
  const [editingRule, setEditingRule] = useState<Partial<WatermarkRule>>({
    name: '',
    priority: 500,
    audience: 'ALL',
    planCode: 'EXPLORER',
    outputType: 'ALL',
    enabled: true,
    isCleanOutput: false,
  });

  // Sandbox Tester State
  const [testContext, setTestContext] = useState({
    userName: 'Sarah Connor',
    audience: 'CONSUMER',
    planCode: 'EXPLORER',
    outputType: 'PDF',
    tripName: 'Paris & Swiss Alps 7-Day Tour',
    companyName: 'AITravelglobe',
  });
  const [testResult, setTestResult] = useState<WatermarkTestResult | null>(null);

  const loadData = async () => {
    setLoading(true);
    try {
      const [wmList, ruleList] = await Promise.all([
        watermarkService.getAllWatermarks(),
        watermarkService.getAllRules(),
      ]);
      setWatermarks(wmList);
      setRules(ruleList);
    } catch (err) {
      console.error('Failed to load watermarks:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  const handleSaveWatermark = async () => {
    if (!editingWm.name) return;
    try {
      if (editingWm.id) {
        await watermarkService.updateWatermark(editingWm.id, editingWm as Watermark);
        enqueueSnackbar('Watermark updated', { variant: 'success' });
      } else {
        await watermarkService.createWatermark(editingWm as Watermark);
        enqueueSnackbar('New watermark created', { variant: 'success' });
      }
      setWmDialogOpen(false);
      loadData();
    } catch (err: any) {
      enqueueSnackbar('Failed to save watermark', { variant: 'error' });
    }
  };

  const handleSaveRule = async () => {
    if (!editingRule.name) return;
    try {
      if (editingRule.id) {
        await watermarkService.updateRule(editingRule.id, editingRule as WatermarkRule);
        enqueueSnackbar('Rule updated', { variant: 'success' });
      } else {
        await watermarkService.createRule(editingRule as WatermarkRule);
        enqueueSnackbar('New rule added to priority engine', { variant: 'success' });
      }
      setRuleDialogOpen(false);
      loadData();
    } catch (err: any) {
      enqueueSnackbar('Failed to save rule', { variant: 'error' });
    }
  };

  const handleRunSandboxTest = async () => {
    try {
      const res = await watermarkService.testWatermarkRule(testContext);
      setTestResult(res);
      enqueueSnackbar('Evaluated watermark rule hierarchy', { variant: 'info' });
    } catch (err) {
      enqueueSnackbar('Failed to run test', { variant: 'error' });
    }
  };

  return (
    <Box sx={{ p: { xs: 2, md: 3 } }}>
      <PageHeader
        title="Watermark & Rule Priority Studio"
        subtitle="Manage dynamic watermarks, priority-based resolution rules, and test outputs in real-time"
        action={
          <Stack direction="row" spacing={1.5}>
            <Button
              variant="outlined"
              startIcon={<Add />}
              onClick={() => {
                setEditingRule({ priority: 500, audience: 'ALL', planCode: 'EXPLORER', outputType: 'ALL', enabled: true });
                setRuleDialogOpen(true);
              }}
              sx={{ fontWeight: 800 }}
            >
              Add Priority Rule
            </Button>
            <Button
              variant="contained"
              startIcon={<Add />}
              onClick={() => {
                setEditingWm({ fontSize: 18, fontColorHex: '#94A3B8', opacity: 0.25, rotationDegrees: -30, position: 'CENTER', repeatAcrossPage: true });
                setWmDialogOpen(true);
              }}
              sx={{ fontWeight: 800 }}
            >
              Create Watermark
            </Button>
          </Stack>
        }
      />

      <Grid container spacing={3}>
        {/* Left Column: Watermarks & Priority Rules */}
        <Grid item xs={12} md={7}>
          <GlassCard sx={{ p: 2.5, mb: 3 }}>
            <Typography variant="h6" sx={{ fontWeight: 800, mb: 2 }}>
              Priority Rule Hierarchy (Highest Wins)
            </Typography>
            <Stack spacing={1.5}>
              {rules.map((r, idx) => (
                <Paper
                  key={r.id || idx}
                  variant="outlined"
                  sx={{
                    p: 2,
                    borderRadius: '12px',
                    borderLeft: `5px solid ${r.isCleanOutput ? '#22c55e' : '#3b82f6'}`,
                  }}
                >
                  <Stack direction="row" justifyContent="space-between" alignItems="center">
                    <Box>
                      <Stack direction="row" spacing={1} alignItems="center">
                        <Chip
                          label={`Priority ${r.priority}`}
                          size="small"
                          color={r.priority >= 800 ? 'warning' : 'primary'}
                          sx={{ fontWeight: 900 }}
                        />
                        <Typography variant="subtitle2" sx={{ fontWeight: 800 }}>
                          {r.name}
                        </Typography>
                      </Stack>
                      <Typography variant="caption" color="text.secondary" sx={{ mt: 0.5, display: 'block' }}>
                        Matches: Plan: <strong>{r.planCode || 'ALL'}</strong> • Audience: <strong>{r.audience || 'ALL'}</strong> • Output: <strong>{r.outputType || 'ALL'}</strong>
                      </Typography>
                    </Box>
                    <Chip
                      label={r.isCleanOutput ? 'Clean Output (No Watermark)' : 'Watermarked'}
                      size="small"
                      color={r.isCleanOutput ? 'success' : 'default'}
                      variant="outlined"
                      sx={{ fontWeight: 700 }}
                    />
                  </Stack>
                </Paper>
              ))}
            </Stack>
          </GlassCard>

          <GlassCard sx={{ p: 2.5 }}>
            <Typography variant="h6" sx={{ fontWeight: 800, mb: 2 }}>
              Registered Watermark Designs
            </Typography>
            <Grid container spacing={2}>
              {watermarks.map((wm) => (
                <Grid item xs={12} sm={6} key={wm.id}>
                  <Card variant="outlined" sx={{ borderRadius: '12px', position: 'relative', overflow: 'hidden' }}>
                    <Box
                      sx={{
                        height: 100,
                        bgcolor: '#0f172a',
                        display: 'flex',
                        alignItems: 'center',
                        justifyContent: 'center',
                        position: 'relative',
                        color: wm.fontColorHex || '#fff',
                        opacity: 0.8,
                      }}
                    >
                      <Typography
                        sx={{
                          fontSize: '0.85rem',
                          fontWeight: 800,
                          transform: `rotate(${wm.rotationDegrees || 0}deg)`,
                          opacity: wm.opacity || 0.3,
                          textAlign: 'center',
                          px: 2,
                        }}
                      >
                        {wm.textTemplate}
                      </Typography>
                    </Box>
                    <CardContent sx={{ p: 1.5 }}>
                      <Typography variant="subtitle2" sx={{ fontWeight: 800 }}>
                        {wm.name}
                      </Typography>
                      <Typography variant="caption" color="text.secondary">
                        Type: {wm.type} • Opacity: {Math.round((wm.opacity || 0.25) * 100)}%
                      </Typography>
                    </CardContent>
                  </Card>
                </Grid>
              ))}
            </Grid>
          </GlassCard>
        </Grid>

        {/* Right Column: Live Sandbox Rule Tester */}
        <Grid item xs={12} md={5}>
          <GlassCard sx={{ p: 2.5 }}>
            <Typography variant="h6" sx={{ fontWeight: 800, mb: 1 }}>
              Live Rule Resolution Sandbox
            </Typography>
            <Typography variant="caption" color="text.secondary" sx={{ display: 'block', mb: 2 }}>
              Simulate any user context to test which watermark rule evaluates and wins.
            </Typography>

            <Stack spacing={2}>
              <TextField
                fullWidth
                size="small"
                label="Simulated Traveler Name"
                value={testContext.userName}
                onChange={(e) => setTestContext({ ...testContext, userName: e.target.value })}
              />
              <TextField
                select
                fullWidth
                size="small"
                label="Subscription Plan"
                value={testContext.planCode}
                onChange={(e) => setTestContext({ ...testContext, planCode: e.target.value })}
              >
                <MenuItem value="FREE">FREE Starter</MenuItem>
                <MenuItem value="EXPLORER">EXPLORER ($2.99/mo)</MenuItem>
                <MenuItem value="BUSINESS">BUSINESS ($39/mo)</MenuItem>
                <MenuItem value="PRO">PRO Custom</MenuItem>
              </TextField>
              <TextField
                select
                fullWidth
                size="small"
                label="Output Medium"
                value={testContext.outputType}
                onChange={(e) => setTestContext({ ...testContext, outputType: e.target.value })}
              >
                <MenuItem value="PDF">PDF Export</MenuItem>
                <MenuItem value="IN_APP">In-App Screen View</MenuItem>
                <MenuItem value="WORD">Word DOCX Export</MenuItem>
                <MenuItem value="SHARED_LINK">Public Share Link</MenuItem>
              </TextField>

              <Button
                variant="contained"
                startIcon={<PlayArrow />}
                onClick={handleRunSandboxTest}
                sx={{ fontWeight: 800, py: 1.2 }}
              >
                Evaluate Rules
              </Button>
            </Stack>

            {testResult && (
              <Box sx={{ mt: 3, p: 2, borderRadius: '12px', bgcolor: 'action.hover' }}>
                <Typography variant="subtitle2" sx={{ fontWeight: 800, mb: 1 }}>
                  EVALUATION RESULT:
                </Typography>
                <Typography variant="body2">
                  <strong>Winning Rule:</strong> {testResult.ruleName} (Priority {testResult.matchedPriority})
                </Typography>
                <Typography variant="body2">
                  <strong>Apply Watermark:</strong>{' '}
                  <Chip
                    label={testResult.applyWatermark ? 'YES' : 'NO (CLEAN OUTPUT)'}
                    size="small"
                    color={testResult.applyWatermark ? 'warning' : 'success'}
                    sx={{ fontWeight: 800, ml: 0.5 }}
                  />
                </Typography>
                {testResult.resolvedText && (
                  <Alert severity="info" sx={{ mt: 1.5 }}>
                    <strong>Resolved Text:</strong> {testResult.resolvedText}
                  </Alert>
                )}
              </Box>
            )}
          </GlassCard>
        </Grid>
      </Grid>

      {/* Watermark Dialog */}
      <Dialog open={wmDialogOpen} onClose={() => setWmDialogOpen(false)} maxWidth="sm" fullWidth>
        <DialogTitle sx={{ fontWeight: 800 }}>Create / Edit Watermark Design</DialogTitle>
        <DialogContent dividers>
          <Stack spacing={2} sx={{ mt: 1 }}>
            <TextField
              fullWidth
              label="Watermark Name"
              value={editingWm.name || ''}
              onChange={(e) => setEditingWm({ ...editingWm, name: e.target.value })}
            />
            <TextField
              fullWidth
              multiline
              rows={2}
              label="Text Template (supports {{USER_NAME}}, {{COMPANY_NAME}}, {{DATE}})"
              value={editingWm.textTemplate || ''}
              onChange={(e) => setEditingWm({ ...editingWm, textTemplate: e.target.value })}
            />
            <Typography variant="caption" sx={{ fontWeight: 700 }}>
              Opacity ({Math.round((editingWm.opacity || 0.25) * 100)}%):
            </Typography>
            <Slider
              value={editingWm.opacity || 0.25}
              min={0.05}
              max={1.0}
              step={0.05}
              onChange={(_, v) => setEditingWm({ ...editingWm, opacity: v as number })}
            />
            <Typography variant="caption" sx={{ fontWeight: 700 }}>
              Rotation ({editingWm.rotationDegrees || 0}°):
            </Typography>
            <Slider
              value={editingWm.rotationDegrees || 0}
              min={-45}
              max={45}
              step={5}
              onChange={(_, v) => setEditingWm({ ...editingWm, rotationDegrees: v as number })}
            />
          </Stack>
        </DialogContent>
        <DialogActions sx={{ p: 2 }}>
          <Button onClick={() => setWmDialogOpen(false)}>Cancel</Button>
          <Button variant="contained" onClick={handleSaveWatermark} sx={{ fontWeight: 800 }}>
            Save Watermark
          </Button>
        </DialogActions>
      </Dialog>

      {/* Rule Dialog */}
      <Dialog open={ruleDialogOpen} onClose={() => setRuleDialogOpen(false)} maxWidth="sm" fullWidth>
        <DialogTitle sx={{ fontWeight: 800 }}>Configure Watermark Priority Rule</DialogTitle>
        <DialogContent dividers>
          <Stack spacing={2} sx={{ mt: 1 }}>
            <TextField
              fullWidth
              label="Rule Name"
              value={editingRule.name || ''}
              onChange={(e) => setEditingRule({ ...editingRule, name: e.target.value })}
            />
            <TextField
              fullWidth
              type="number"
              label="Priority (e.g. 900 for B2B, 500 for Explorer, 100 for Free)"
              value={editingRule.priority ?? 500}
              onChange={(e) => setEditingRule({ ...editingRule, priority: parseInt(e.target.value) || 100 })}
            />
            <TextField
              select
              fullWidth
              label="Plan Code Match"
              value={editingRule.planCode || 'ALL'}
              onChange={(e) => setEditingRule({ ...editingRule, planCode: e.target.value })}
            >
              <MenuItem value="ALL">ALL Plans</MenuItem>
              <MenuItem value="FREE">FREE</MenuItem>
              <MenuItem value="EXPLORER">EXPLORER</MenuItem>
              <MenuItem value="BUSINESS">BUSINESS</MenuItem>
            </TextField>
            <TextField
              select
              fullWidth
              label="Action"
              value={editingRule.isCleanOutput ? 'CLEAN' : 'WATERMARK'}
              onChange={(e) => setEditingRule({ ...editingRule, isCleanOutput: e.target.value === 'CLEAN' })}
            >
              <MenuItem value="WATERMARK">Apply Watermark Template</MenuItem>
              <MenuItem value="CLEAN">Clean Output (Suppress All Watermarks)</MenuItem>
            </TextField>
          </Stack>
        </DialogContent>
        <DialogActions sx={{ p: 2 }}>
          <Button onClick={() => setRuleDialogOpen(false)}>Cancel</Button>
          <Button variant="contained" onClick={handleSaveRule} sx={{ fontWeight: 800 }}>
            Save Rule
          </Button>
        </DialogActions>
      </Dialog>
    </Box>
  );
};

export default WatermarkStudioPage;
